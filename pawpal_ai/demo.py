"""Reproducible end-to-end demo scenarios and the execution-log writer (ai_interactions.md)."""

from __future__ import annotations

import os
import re
from datetime import datetime, timedelta
from typing import List, Optional, Tuple

from pawpal_system import Owner, Pet, Task

from .history import PetHistoryManager
from .integration import schedule_vet_followup
from .models import AnalysisReport, ImageInput
from .pipeline import StoolAnalysisPipeline
from .report import render_text

DEMO_NOW = datetime(2026, 11, 24, 18, 0, 0)
BEGIN, END = "<!-- BEGIN RUNTIME TRACE (generated by `python -m pawpal_ai.cli demo`) -->", "<!-- END RUNTIME TRACE -->"
SAMPLE_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "sample_images")


def build_demo_owner(now: datetime = DEMO_NOW) -> Owner:
    """Alex with Luna (dog) and Mochi (cat), including feeding/medication tasks and a recent diet change."""
    def d(days: int) -> str:
        return (now.date() + timedelta(days=days)).strftime("%Y-%m-%d")

    owner = Owner("Alex", "alex@example.com")
    luna = owner.add_pet(Pet("Luna", "Dog", "Labrador", 4))
    mochi = owner.add_pet(Pet("Mochi", "Cat", "Siamese", 2))
    for day in (-12, -9):
        luna.add_task(Task("Dinner (usual kibble)", "17:30", d(day), "Feeding", "High", 15, "Completed", "Daily"))
    luna.add_task(Task("Dinner (new salmon kibble)", "17:30", d(-2), "Feeding", "High", 15, "Completed", "Daily"))
    luna.add_task(Task("Heartworm pill", "12:00", d(-1), "Medication", "High", 5, "Completed"))
    luna.add_task(Task("Morning walk", "07:30", d(1), "Exercise", "High", 30, "Pending", "Daily"))
    mochi.add_task(Task("Breakfast", "07:45", d(0), "Feeding", "High", 15, "Pending", "Daily"))
    return owner


def seed_history(pet: Pet, now: datetime = DEMO_NOW) -> None:
    """Add clearly-labelled SEEDED prior observations (normal, brown) so trend comparison has data."""
    for days, score in ((6, 2), (4, 3), (2, 2)):
        ts = (now - timedelta(days=days)).isoformat(timespec="seconds")
        PetHistoryManager.add(pet, {
            "report_id": f"seed{days}", "timestamp": ts, "image_name": "(seeded demo record)", "image_sha256": "",
            "species": "dog", "score": score, "category": "firm, well formed" if score == 2 else "soft but formed",
            "color": "brown", "flags": [], "confidence": 0.6, "escalation": "none"})


# (label, pet, image file, hours after DEMO_NOW start, symptoms, schedule vet?)
SCENARIOS: List[Tuple[str, str, str, int, Tuple[str, ...], bool]] = [
    ("1. Normal-looking stool (dog, with seeded history)", "Luna", "normal_log.png", 0, (), False),
    ("2. Loose stool + recent diet change (dog)", "Luna", "loose_piles.png", 24, (), False),
    ("3. Possible red discoloration, schedule vet visit", "Luna", "red_streaks.png", 48, (), True),
    ("4. Cat: descriptive category only, no numeric score", "Mochi", "normal_firm_log.png", 48, (), False),
    ("5. Repeated loose stool + reported symptoms", "Luna", "loose_spots.png", 72, ("vomiting", "lethargy"), False),
    ("6. Blurry photo (rejected for quality)", "Luna", "blurry_photo.png", 72, (), False),
    ("7. Invalid file (rejected as input)", "Luna", "invalid_not_an_image.jpg", 72, (), False),
]


def run_demo(pipeline: Optional[StoolAnalysisPipeline] = None, verbose: bool = True) -> List[Tuple[str, AnalysisReport]]:
    """Run every scenario against an in-memory owner and return (label, report) pairs."""
    pipeline = pipeline or StoolAnalysisPipeline()
    owner = build_demo_owner()
    seed_history(owner.get_pet("Luna"))
    out: List[Tuple[str, AnalysisReport]] = []
    for label, pet_name, filename, hours, symptoms, book in SCENARIOS:
        pet = owner.get_pet(pet_name)
        path = os.path.join(SAMPLE_DIR, filename)
        when = DEMO_NOW + timedelta(hours=hours)
        report = pipeline.analyze(pet, ImageInput.from_path(path), symptoms=symptoms, now=when)
        out.append((label, report))
        if verbose:
            print("\n" + "#" * 74 + f"\n# {label}\n" + "#" * 74)
            print(render_text(report, show_trace=False) if report.status == "completed" and label[0] in "1235"
                  else render_text(report))
            if book:
                task = schedule_vet_followup(owner, pet, report)
                print(f"\n>> Scheduler integration: {'added ' + repr(task) if task else 'no task added'}")
    return out


def write_execution_log(runs: List[Tuple[str, AnalysisReport]], path: str) -> None:
    """Insert/replace the generated runtime-trace section of ai_interactions.md."""
    lines = [BEGIN, "", "## Part 4 - Runtime agentic workflow records (generated)", "",
             "Each analysis runs a fixed multi-stage workflow. The tables below are the concise, auditable execution records "
             "(stage, outcome, key values, duration) captured by the pipeline during `python -m pawpal_ai.cli demo`. "
             "They contain actions, validation results and decisions only; no private reasoning. "
             "Demo history for Luna is **seeded** and the images are **synthetic**.", ""]
    for label, r in runs:
        lines += [f"### {label}", "", f"- Result: `{r.status}`" + (f", score `{r.classification.score}`, category `{r.classification.category}`" if r.classification else "")
                  + f", escalation `{r.escalation.level}`, safety validation `{'passed' if r.validation.passed else 'FAILED'}`", "",
                  "| Stage | Status | ms | Record |", "|---|---|---:|---|"]
        for s in r.trace:
            detail = s.detail.replace("|", "/")
            lines.append(f"| {s.stage} | {s.status} | {s.duration_ms:.1f} | {detail} |")
        lines.append("")
    lines += [END, ""]
    block = "\n".join(lines)
    existing = ""
    if os.path.exists(path):
        with open(path, "r", encoding="utf-8") as handle:
            existing = handle.read()
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?", re.S)
    new = pattern.sub(lambda _m: block, existing) if pattern.search(existing) else existing.rstrip() + "\n\n---\n\n" + block
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(new)
